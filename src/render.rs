use crate::{
    config::{Config, Host},
    resolver::{self, ResolvedHost},
    util,
};
use anyhow::{Context, Result, ensure};
use std::collections::BTreeSet;

pub const HEADER: &str = "# Generated by sshweave; DO NOT EDIT.\n";

fn ssh_quote(input: &str) -> Result<String> {
    util::single_line(input)?;
    Ok(format!(
        "\"{}\"",
        input.replace('\\', "\\\\").replace('"', "\\\"")
    ))
}

fn ssh_options(output: &mut String, options: &Host) -> Result<()> {
    for (key, value) in &options.ssh {
        for line in value.lines() {
            let line = util::expand_env(&line)?;
            util::single_line(&line)?;
            // Values are OpenSSH argument expressions (e.g. LocalForward "8080 localhost:80").
            output.push_str(&format!("  {key} {line}\n"));
        }
    }
    Ok(())
}

fn stanza(
    output: &mut String,
    host: &ResolvedHost,
    wildcard: bool,
    exclusions: &[String],
) -> Result<()> {
    output.push_str(&format!(
        "\nHost {}{}\n",
        host.name,
        if exclusions.is_empty() {
            String::new()
        } else {
            format!(" {}", exclusions.join(" "))
        }
    ));
    if let Some(comment) = &host.options.comment {
        for line in comment.lines() {
            output.push_str(&format!("  # {line}\n"));
        }
    }
    let hostname = if wildcard {
        host.options
            .hostname
            .as_deref()
            .unwrap_or("%h")
            .replace("%n", "%h")
    } else {
        host.hostname.clone()
    };
    ensure!(
        !hostname.contains(['{', '}']),
        "capture substitution requires a concrete target"
    );
    output.push_str(&format!(
        "  HostName {}\n  User {}\n  Port {}\n",
        ssh_quote(&util::expand_env(&hostname)?)?,
        ssh_quote(&host.user)?,
        host.port
    ));
    if let Some(seconds) = host.options.connect_timeout {
        output.push_str(&format!("  ConnectTimeout {seconds}\n"));
    }
    ssh_options(output, &host.options)?;
    Ok(())
}

pub fn ssh_config(
    config: &Config,
    known: &BTreeSet<String>,
    automatic_rewrite: bool,
) -> Result<String> {
    let mut output = HEADER.to_owned();
    output.push_str(&format!("# sshweave {}\n", env!("CARGO_PKG_VERSION")));
    let mut names = config.concrete_names();
    names.extend(known.iter().cloned());
    let names = config.route_targets(names)?;
    for name in &names {
        util::valid_target(name)?;
        stanza(&mut output, &config.resolve(name)?, false, &[])?;
    }
    let concrete_exclusions = names
        .iter()
        .map(|name| format!("!{name}"))
        .collect::<Vec<_>>();
    for (pattern, host) in &config.document.hosts {
        for pattern in std::iter::once(pattern).chain(host.aliases.iter()) {
            if !resolver::is_pattern(pattern) || pattern.starts_with("regex:") {
                continue;
            }
            let resolved = config.resolve_inner(pattern)?;
            stanza(&mut output, &resolved, true, &concrete_exclusions)?;
        }
    }
    let defaults = config.inherit_defaults()?;
    let mut exclusions = concrete_exclusions;
    for (pattern, host) in &config.document.hosts {
        exclusions.extend(
            std::iter::once(pattern)
                .chain(host.aliases.iter())
                .filter(|p| resolver::is_pattern(p) && !p.starts_with("regex:"))
                .map(|p| format!("!{p}")),
        );
    }
    output.push_str(&format!("\nHost * {}\n", exclusions.join(" ")));
    ssh_options(&mut output, &defaults)?;
    if let Some(user) = &defaults.user {
        output.push_str(&format!(
            "  User {}\n",
            ssh_quote(&util::expand_env(user)?)?
        ));
    }
    if let Some(port) = defaults.port {
        output.push_str(&format!("  Port {port}\n"));
    }
    if let Some(seconds) = defaults.connect_timeout {
        output.push_str(&format!("  ConnectTimeout {seconds}\n"));
    }
    if let Some(hostname) = &defaults.hostname {
        output.push_str(&format!(
            "  HostName {}\n",
            ssh_quote(&util::expand_env(&hostname.replace("%n", "%h"))?)?
        ));
    }
    let binary = config.binary()?.to_string_lossy().into_owned();
    let source = config
        .source
        .to_str()
        .context("configuration path is not UTF-8")?;
    ensure!(
        !binary.contains('%') && !source.contains('%'),
        "paths used in ProxyCommand cannot contain %"
    );
    let command = format!(
        "{} --config {} connect --port %p --user %r {}-- %n",
        shell_words::quote(&binary),
        shell_words::quote(source),
        if automatic_rewrite {
            ""
        } else {
            "--no-rewrite "
        }
    );
    // ProxyCommand retains its shell quoting; unlike normal SSH values, do not quote the whole line.
    util::single_line(&command)?;
    output.push_str(&format!("\nHost *\n  ProxyCommand {command}\n"));
    Ok(output)
}

pub fn graphviz(config: &Config) -> Result<String> {
    fn quoted(s: &str) -> Result<String> {
        Ok(serde_json::to_string(s)?)
    }
    fn parent_node(config: &Config, parent: &str) -> String {
        if let Some(name) = parent.strip_prefix("host:") {
            name.to_owned()
        } else if parent.starts_with("template:") {
            parent.to_owned()
        } else if config.document.templates.contains_key(parent) {
            format!("template:{parent}")
        } else {
            parent.to_owned()
        }
    }
    let mut output = String::from("digraph sshweave {\n  rankdir=LR;\n");
    for name in config.document.proxies.keys() {
        output.push_str(&format!(
            "  {} [shape=box];\n",
            quoted(&format!("proxy:{name}"))?
        ));
    }
    for (name, host) in &config.document.templates {
        output.push_str(&format!(
            "  {} [shape=box,style=dashed];\n",
            quoted(&format!("template:{name}"))?
        ));
        for parent in &host.inherits {
            output.push_str(&format!(
                "  {} -> {} [style=dashed,label=\"inherits\"];\n",
                quoted(&format!("template:{name}"))?,
                quoted(&parent_node(config, parent))?
            ));
        }
    }
    for (name, host) in &config.document.hosts {
        output.push_str(&format!("  {} [shape=ellipse];\n", quoted(name)?));
        let resolved = config.resolve_inner(name)?;
        if let Some(proxy) = &resolved.options.proxy {
            output.push_str(&format!(
                "  {} -> {} [style=dotted,label=\"proxy\"];\n",
                quoted(name)?,
                quoted(&format!("proxy:{proxy}"))?
            ));
        }
        for gateway in resolved.routes().into_iter().filter(|g| g != "direct") {
            output.push_str(&format!(
                "  {} -> {} [label={}];\n",
                quoted(name)?,
                quoted(&gateway)?,
                quoted(&format!("gateway ({})", resolved.gateway_strategy.as_str()))?
            ));
        }
        for parent in &host.inherits {
            let parent = parent_node(config, parent);
            output.push_str(&format!(
                "  {} -> {} [style=dashed,label=\"inherits\"];\n",
                quoted(name)?,
                quoted(&parent)?
            ));
        }
        for alias in &host.aliases {
            output.push_str(&format!(
                "  {} -> {} [style=dotted,label=\"alias\"];\n",
                quoted(alias)?,
                quoted(name)?
            ));
        }
    }
    output.push_str("}\n");
    Ok(output)
}
